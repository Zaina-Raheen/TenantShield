import { Link, useParams } from "react-router-dom";
import { api } from "../api";
import type { Finding } from "../types";
import { Badge, Empty, ErrorNote, Evidence, fmt, KV, Loading, PageHeader, RegBadge, Section, Table, useBusy, useLoad } from "../ui";

export function Findings() {
  const { data, error, loading } = useLoad(api.findings);
  return (
    <>
      <PageHeader title="Findings" sub="Confirmed tenant-isolation failures. Each finding keeps its original detection; later detections are added to its history." />
      <ErrorNote message={error} />
      {loading ? <Loading /> : !data?.length ? (
        <Empty>No confirmed findings. If the demo is in vulnerable mode, run the isolation tests from the Overview.</Empty>
      ) : (
        <Table head={["Finding", "Severity", "Endpoint", "Requesting → owner", "First run", "Detections", "Last detected", "Regression", ""]}>
          {data.map((f) => (
            <tr key={f.id}>
              <td className="td font-medium">{f.title}</td>
              <td className="td">{f.severity}</td>
              <td className="td code">{f.endpoint}</td>
              <td className="td code">{f.requesting_tenant_id} → {f.resource_owner_tenant_id}</td>
              <td className="td">#{f.first_detected_run_id}</td>
              <td className="td">{f.occurrence_count}</td>
              <td className="td">{fmt(f.last_detected_at)}</td>
              <td className="td"><RegBadge status={f.regression_status} /></td>
              <td className="td"><Link className="text-accent underline" to={`/findings/${f.id}`}>Open</Link></td>
            </tr>))}
        </Table>)}
    </>
  );
}

interface TimelineEvent { at: string; status: string; title: string; note: string; mode: string }

function timelineEvents(f: Finding): TimelineEvent[] {
  const suite = [...(f.occurrences ?? [])].filter((o) => o.source === "suite").reverse();  // oldest first
  const ev: TimelineEvent[] = suite.map((o, i) => ({
    at: o.detected_at, status: "finding", mode: o.demo_mode,
    title: i === 0 ? `Original detection in run #${o.run_id}` : `Detected again in run #${o.run_id}`,
    note: i === 0 ? f.actual_behavior : "Same finding confirmed by a later test run.",
  }));
  for (const r of f.regression_history ?? []) {
    const verdict = r.result_status === "passed" ? "Retest passed: access denied"
      : r.result_status === "finding" ? "Retest: still vulnerable"
      : r.result_status === "inconclusive" ? "Retest inconclusive" : "Retest failed unexpectedly";
    ev.push({ at: r.run_at, status: r.result_status, mode: r.demo_mode, title: verdict, note: r.observed_outcome });
  }
  return ev.sort((a, b) => a.at.localeCompare(b.at));
}

function buildReport(f: Finding): string {
  const events = timelineEvents(f);
  return [`# ${f.title}`, "", `Severity: ${f.severity}`, `Endpoint: GET ${f.endpoint}`,
    `Requesting tenant: ${f.requesting_tenant_id}`, `Resource: ${f.resource_id} (owner ${f.resource_owner_tenant_id})`,
    `Detections: ${f.occurrence_count}`, "", `## Expected`, f.expected_behavior, "", `## Actual (original detection)`, f.actual_behavior, "",
    `## Original evidence (redacted)`, "```json", JSON.stringify(f.original?.evidence ?? f.evidence, null, 2), "```", "",
    `## Timeline`, ...events.map((e) => `- ${fmt(e.at)}: ${e.title} (demo mode: ${e.mode})`),
    "", `## Remediation`, f.remediation ?? "", "",
    "_Generated by TENANTSHIELD. A passing retest means the configured check passed, not that the application is fully secure._"].join("\n");
}

function download(name: string, text: string) {
  const a = document.createElement("a");
  a.href = URL.createObjectURL(new Blob([text], { type: "text/markdown" }));
  a.download = name; a.click(); URL.revokeObjectURL(a.href);
}

function Timeline({ events }: { events: TimelineEvent[] }) {
  return (
    <ol className="ml-2 border-l border-line">
      {events.map((e, i) => (
        <li key={i} className="relative pb-4 pl-5">
          <span className={`absolute -left-[5px] top-1.5 h-2.5 w-2.5 rounded-full ${e.status === "passed" ? "bg-ok" : e.status === "finding" ? "bg-fail" : "bg-muted"}`} />
          <div className="font-medium">{e.title}</div>
          <div className="text-[12px] text-muted">{fmt(e.at)} · demo mode: {e.mode}</div>
          <div className="text-[13px]">{e.note}</div>
        </li>))}
    </ol>
  );
}

export function FindingDetail() {
  const { id } = useParams();
  const { data: f, error, loading, reload } = useLoad(() => api.finding(id!), [id]);
  const { busy, err, wrap } = useBusy();
  if (loading && !f) return <Loading />;
  if (!f) return <ErrorNote message={error} />;
  const reg = f.regression;
  const original = f.original!;
  const latest = f.latest_occurrence;
  const latestIsOriginal = !latest || (latest.source === "suite" && latest.run_id === original.run_id);
  const events = timelineEvents(f);
  const latestRetest = f.latest_regression_result;

  return (
    <>
      <PageHeader title={f.title}
        sub={`Severity ${f.severity} · first detected in run #${original.run_id} (${fmt(original.detected_at)}) · detected ${f.occurrence_count} time(s)`}
        action={<div className="flex gap-2">
          <button className="btn" onClick={() => download(`tenantshield-finding-${f.id}.md`, buildReport(f))}>Download evidence report</button>
          {!reg && <button className="btn btn-primary" disabled={busy}
            onClick={() => wrap(async () => { await api.saveRegression(f.id); reload(); })}>Save as regression test</button>}</div>} />
      <ErrorNote message={err || error} />

      <Section title="What happened">
        <p className="max-w-[70ch]">An identity from <b>{f.requesting_tenant_name}</b> requested <span className="code">{f.resource_id}</span>,
          which belongs to <b>{f.resource_owner_tenant_name}</b>, and the API returned it. This is a confirmed tenant-isolation failure.</p>
      </Section>

      <Section title="Test context">
        <dl className="panel px-4 py-2">
          <KV k="Requesting tenant" v={`${f.requesting_tenant_name} (${f.requesting_tenant_id})`} />
          <KV k="Endpoint" v={<span className="code">GET {f.endpoint}</span>} />
          <KV k="Resource" v={<span className="code">{f.resource_id}</span>} />
          <KV k="Resource owner" v={`${f.resource_owner_tenant_name} (${f.resource_owner_tenant_id})`} />
        </dl>
      </Section>

      <Section title="Expected vs actual">
        <div className="grid gap-3 md:grid-cols-2">
          <div className="panel border-ok/40 p-4"><div className="mb-1 text-[12px] font-medium text-ok">Expected</div>{f.expected_behavior}</div>
          <div className="panel border-fail/40 p-4"><div className="mb-1 text-[12px] font-medium text-fail">Actual (original detection)</div>{f.actual_behavior}</div>
        </div>
      </Section>

      <Section title="Original evidence">
        <p className="mb-2 text-muted">Recorded in run #{original.run_id} with the demo in {original.demo_mode} mode. Never modified.</p>
        <Evidence value={original.evidence} />
      </Section>

      {!latestIsOriginal && latest && (
        <Section title="Latest occurrence">
          <p className="mb-2 text-muted">
            {latest.source === "suite" ? `Test run #${latest.run_id}` : `Regression retest #${latest.regression_run_id}`} · {fmt(latest.detected_at)} · demo {latest.demo_mode}
          </p>
          <Evidence value={latest.evidence} />
        </Section>)}

      <Section title="Remediation guidance"><p className="max-w-[70ch]">{f.remediation}</p></Section>

      {events.length > 1 && <Section title="Proof timeline"><Timeline events={events} /></Section>}

      <Section title="Regression">
        {!reg ? <p className="text-muted">
          {latestRetest ? "The earlier regression test was deleted (its history is kept above). Save a new one to retest." :
            "Not saved yet. Save this finding to keep a reusable test, then rerun it after fixing the API."}</p> : (
          <div className="panel p-4">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <Link className="font-medium text-accent underline" to={`/regression/${reg.id}`}>{reg.name}</Link>
              <button className="btn" disabled={busy} onClick={() => wrap(async () => { await api.runRegression(reg.id); reload(); })}>
                {busy ? "Running…" : "Run test again"}</button>
            </div>
            <div className="mt-3 grid gap-3 md:grid-cols-2">
              <div><div className="mb-1 text-[12px] text-muted">Original failure</div>
                <Badge status="finding" /> <span className="text-muted">run #{original.run_id}, {fmt(original.detected_at)}</span></div>
              <div><div className="mb-1 text-[12px] text-muted">Latest retest</div>
                {latestRetest ? <><RegBadge status={latestRetest.status} /> <span className="text-muted">{fmt(latestRetest.run_at)}</span></>
                  : <span className="text-muted">Not rerun yet</span>}</div>
            </div>
          </div>)}
      </Section>
    </>
  );
}
